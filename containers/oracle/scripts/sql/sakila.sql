DEFINE CONNECT_STRING=&&1
DEFINE SAKILA_DIR=&&2

SET ECHO ON
SET TERMOUT ON
DROP USER SAKILA CASCADE;
/

WHENEVER OSERROR EXIT 1
WHENEVER SQLERROR EXIT 1
CREATE USER SAKILA IDENTIFIED BY sakila;
GRANT CONNECT,
      RESOURCE,
      CREATE VIEW,
      UNLIMITED TABLESPACE
      TO SAKILA;
GRANT EXECUTE ON DBMS_STATS TO SAKILA;
/

CONNECT SAKILA/sakila&CONNECT_STRING

@&SAKILA_DIR/oracle-sakila-schema.sql
@&SAKILA_DIR/oracle-sakila-schema-pl-sql.sql
@&SAKILA_DIR/oracle-sakila-insert-data.sql
