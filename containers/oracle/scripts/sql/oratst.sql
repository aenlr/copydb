-- Create an initial empty ORATST schema to use for testing.
-- sqlplus "SYS/<PWD>@<CONN> as sysdba" @oratst.sql
CREATE USER ORATST IDENTIFIED BY ORATST;
GRANT CONNECT, RESOURCE, CREATE VIEW, DBA, UNLIMITED TABLESPACE TO ORATST;
GRANT EXECUTE ON DBMS_STATS   TO ORATST;
GRANT SELECT  ON V_$STATNAME  TO ORATST;
GRANT SELECT  ON V_$MYSTAT    TO ORATST;
GRANT SELECT  ON V_$TIMER     TO ORATST;
GRANT SELECT  ON V_$LATCH     TO ORATST;
/
