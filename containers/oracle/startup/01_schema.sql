ALTER SESSION SET CONTAINER=XEPDB1;

DEFINE USERNAME = 'ORATST'

DECLARE
    L_EXISTS NUMBER;
BEGIN
  SELECT COUNT(*) INTO L_EXISTS FROM DBA_USERS WHERE USERNAME = '&USERNAME';
  IF (L_EXISTS = 0) THEN
    EXECUTE IMMEDIATE 'CREATE USER &USERNAME IDENTIFIED BY &USERNAME';
  END IF;
END;
/

GRANT CONNECT, RESOURCE, CREATE VIEW, DBA, UNLIMITED TABLESPACE TO &USERNAME;
GRANT EXECUTE ON DBMS_STATS   TO &USERNAME;
GRANT SELECT  ON V_$STATNAME  TO &USERNAME;
GRANT SELECT  ON V_$MYSTAT    TO &USERNAME;
GRANT SELECT  ON V_$TIMER     TO &USERNAME;
GRANT SELECT  ON V_$LATCH     TO &USERNAME;
/

